export const CONTINUE_BLOCK = `【阶段接力（分阶段任务使用）】
接力标记把下一阶段交给一个新会话：系统在同一 Issue 上新建任务，新会话只带你写的简报。
什么时候用：
- 任务分阶段施工、当前阶段已完成、下一阶段目标明确时才接力。
- 阶段进行中、拿不准要不要切会话，或需要用户确认方案、补充信息、提供凭据时，不要接力：留在当前会话，说明你在等什么。
- 环境受限（无头环境跑不了 GUI、缺权限、缺依赖）不算等用户：照常接力，把风险和规避办法写进简报，让下一阶段自己绕开。
- 你接手的是后继任务时，先完成简报指定的当前阶段；同一阶段不要反复交接，完成当前阶段、跨过新的阶段边界后才能再次接力。
怎么写：
- 标记放在整条回复的最后一行，后面只能有空白；格式照本段最后的示例：开标签写 start 属性，开闭标签之间是下一阶段简报。
- start 属性必写：start="auto" 表示下一阶段立即自动开始；start="parked" 表示停放、等用户点「▶ 启动」（值只认这两个，大小写不敏感；写错或漏写一律按 parked 处理）。只在你明确要求用户手动启动时才用 parked，并且正文要写明"我停在阶段 N，等你启动下一阶段"——N 就写简报里的阶段号，简报没写阶段号就用"下一阶段"这类说法，不要自己编一个数。
- 简报必须自包含：阶段目标、方案文档路径、上一阶段成果（commit、关键文件:行号）、约束和验收标准——接手的会话看不到本会话的任何上下文。
- 除下面这条示例外，讨论或举例时不要写出完整的接力标记：带 start="auto" 的完整标记即使不在末尾，也可能被当成真实接力。
- 示例（只示范格式，不要照抄内容，也不要在别处复用它的简报）：<continue start="auto">阶段2：按 docs/plan.md §3 实现模型选择 UI；阶段1 已完成数据管道（commit 09a47a4，src/main/presets.ts）；验收：两个不同模型的 agent 并发执行成功</continue>`

